"""Downloads the NASA data the game bundles and converts it to small CSV files.

Run from the repository root, then rebuild the jar:

    python tools/fetch_nasa_data.py [weather] [events] [terrain]
    java Build.java

With no arguments all three archives are refreshed. Needs Python 3.9+ and no packages.
Raw downloads are cached in build/data-cache/ so a re-run does not hit the servers again;
delete that folder to force a fresh download.

Outputs (all are read from inside the jar at run time):

    src/outpost/weather/curiosity_weather.csv    one row per sol measured by Curiosity
    src/outpost/radiation/donki_mars_cme.csv     one row per day a solar storm was
                                                 predicted to reach Mars
    src/outpost/view/gale_terrain.csv            ground heights around Curiosity's
                                                 landing site
"""

import csv
import datetime as dt
import json
import pathlib
import struct
import sys
import time
import urllib.request

ROOT = pathlib.Path(__file__).resolve().parent.parent
CACHE = ROOT / "build" / "data-cache"
AGENT = {"User-Agent": "mars-outpost-game-data-fetch"}

WEATHER_URL = "https://mars.nasa.gov/rss/api/?feed=weather&category=msl&feedtype=json"
DONKI_URL = "https://ccmc.gsfc.nasa.gov/DONKI/WS/get/WSAEnlilSimulations"
MOLA_URL = ("https://pds-geosciences.wustl.edu/mgs/mgs-m-mola-5-megdr-l3-v1/"
            "mgsl_300x/meg128/megt00n090hb.img")

# Curiosity touched down on 2012-08-06 UTC; the feed's first sol is dated 2012-08-07.
FIRST_DATE = dt.date(2012, 8, 1)

# MOLA tile megt00n090hb: 128 pixels per degree, latitude 0 to -44, longitude 90E to 180E,
# 11520 samples by 5632 lines of big-endian signed 16-bit metres above the Mars areoid.
MOLA_PPD = 128
MOLA_SAMPLES = 11520
MOLA_TOP_LAT = 0.0
MOLA_WEST_LON = 90.0
# Bradbury Landing, where Curiosity landed in Gale Crater.
SITE_LAT = -4.5895
SITE_LON = 137.4417
TERRAIN_VERTICES = 21   # 20 x 20 ground tiles
TERRAIN_STRIDE = 2      # MOLA pixels per tile


def fetch(url, headers=None, tries=4):
    request = urllib.request.Request(url, headers={**AGENT, **(headers or {})})
    for attempt in range(tries):
        try:
            with urllib.request.urlopen(request, timeout=120) as response:
                return response.read()
        except Exception as error:  # noqa: BLE001 - retry any network failure
            if attempt == tries - 1:
                raise
            print(f"  retrying after: {error}")
            time.sleep(5 * (attempt + 1))
    raise AssertionError("unreachable")


def cached(name, loader):
    path = CACHE / name
    if not path.exists():
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_bytes(loader())
    return path.read_bytes()


def write_csv(path, comments, header, rows):
    path.parent.mkdir(parents=True, exist_ok=True)
    with open(path, "w", newline="\n", encoding="utf-8") as out:
        for line in comments:
            out.write("# " + line + "\n")
        writer = csv.writer(out, lineterminator="\n")
        writer.writerow(header)
        writer.writerows(rows)
    print(f"wrote {path.relative_to(ROOT)} ({len(rows)} rows)")


def weather():
    raw = cached("msl_weather.json", lambda: fetch(WEATHER_URL))
    soles = json.loads(raw.decode("utf-8", errors="replace"))["soles"]

    def clean(value):
        return "" if value in ("--", None) else str(value).strip()

    rows = []
    for s in sorted(soles, key=lambda s: int(s["sol"])):
        rows.append([
            s["terrestrial_date"], s["sol"], clean(s["ls"]),
            clean(s["min_temp"]), clean(s["max_temp"]),
            clean(s["min_gts_temp"]), clean(s["max_gts_temp"]),
            clean(s["pressure"]), clean(s["local_uv_irradiance_index"]),
            clean(s["sunrise"]), clean(s["sunset"]),
        ])
    write_csv(
        ROOT / "src/outpost/weather/curiosity_weather.csv",
        ["Curiosity rover REMS weather at Gale Crater, Mars. One row per sol.",
         "Source: NASA/JPL-Caltech/CAB(CSIC-INTA), " + WEATHER_URL,
         "Temperatures in degrees Celsius (air, then ground), pressure in pascals,",
         "sunrise and sunset in local Mars time. Empty means not measured that sol.",
         "ls is the solar longitude of Mars in degrees (its position around the Sun).",
         "Archived copy, not live. Generated by tools/fetch_nasa_data.py."],
        ["earth_date", "sol", "ls", "min_air_c", "max_air_c", "min_ground_c",
         "max_ground_c", "pressure_pa", "uv_index", "sunrise", "sunset"],
        rows)


def events():
    today = dt.date.today()
    best = {}  # arrival date -> (speed, cme start, glancing)
    start = FIRST_DATE
    while start <= today:
        end = min(start + dt.timedelta(days=29), today)
        # Only windows that are fully in the past are cached; the newest may still grow.
        name = f"enlil_{start}_{end}.json"
        url = f"{DONKI_URL}?startDate={start}&endDate={end}"
        if end < today:
            raw = cached(name, lambda: (time.sleep(0.5), fetch(url))[1])
        else:
            raw = fetch(url)
        simulations = json.loads(raw) if raw.strip() else []
        for sim in simulations:
            cmes = sim.get("cmeInputs") or []
            if not cmes:
                continue
            fastest = max(cmes, key=lambda c: c.get("speed") or 0)
            for impact in sim.get("impactList") or []:
                if impact.get("location") != "Mars" or impact.get("isMinorImpact"):
                    continue
                arrival = impact["arrivalTime"][:10]
                entry = (int(fastest.get("speed") or 0), fastest["cmeStartTime"][:10],
                         1 if impact.get("isGlancingBlow") else 0)
                # Several model runs often cover one storm. Prefer a direct hit over a
                # glancing blow, then the fastest eruption.
                rank = (-entry[2], entry[0])
                old = best.get(arrival)
                if old is None or rank > (-old[2], old[0]):
                    best[arrival] = entry
        print(f"  {start} to {end}: {len(simulations)} model runs")
        start = end + dt.timedelta(days=1)
    rows = [[day, *best[day]] for day in sorted(best)]
    write_csv(
        ROOT / "src/outpost/radiation/donki_mars_cme.csv",
        ["Days on which a solar storm (coronal mass ejection, CME) was predicted to reach Mars.",
         "Source: NASA CCMC DONKI, WSA-ENLIL solar wind model runs, " + DONKI_URL,
         "These are model predictions of arrival, not measurements made at Mars.",
         "speed_kms is the launch speed of the fastest CME in the model run.",
         "glancing is 1 when the model predicted only the edge of the storm would touch Mars.",
         "Archived copy, not live. Generated by tools/fetch_nasa_data.py."],
        ["arrival_date", "speed_kms", "cme_start_date", "glancing"],
        rows)


def terrain():
    n = TERRAIN_VERTICES
    half = (n - 1) // 2 * TERRAIN_STRIDE
    centre_line = round((MOLA_TOP_LAT - SITE_LAT) * MOLA_PPD - 0.5)
    centre_sample = round((SITE_LON - MOLA_WEST_LON) * MOLA_PPD - 0.5)
    first_line = centre_line - half
    line_count = 2 * half + 1
    record = MOLA_SAMPLES * 2
    first_byte = first_line * record
    last_byte = first_byte + line_count * record - 1
    raw = cached(
        f"mola_lines_{first_line}_{line_count}.bin",
        lambda: fetch(MOLA_URL, {"Range": f"bytes={first_byte}-{last_byte}"}))
    if len(raw) != line_count * record:
        raise SystemExit("MOLA server did not honour the byte range request")

    rows = []
    for row in range(n):  # north to south
        line = row * TERRAIN_STRIDE
        heights = []
        for col in range(n):  # west to east
            sample = centre_sample - half + col * TERRAIN_STRIDE
            (metres,) = struct.unpack_from(">h", raw, line * record + sample * 2)
            heights.append(metres)
        rows.append(heights)
    metres_per_pixel = 3396190 * 3.141592653589793 / 180 / MOLA_PPD
    north = MOLA_TOP_LAT - (first_line + 0.5) / MOLA_PPD
    west = MOLA_WEST_LON + (centre_sample - half + 0.5) / MOLA_PPD
    span = (n - 1) * TERRAIN_STRIDE / MOLA_PPD
    write_csv(
        ROOT / "src/outpost/view/gale_terrain.csv",
        ["Ground heights around Bradbury Landing (Curiosity's landing site), Gale Crater, Mars.",
         "Source: NASA Mars Global Surveyor MOLA gridded topography (MEGDR), 128 pixels per degree,",
         MOLA_URL,
         f"{n} x {n} heights in metres above the Mars reference surface (areoid).",
         "Rows run north to south, columns west to east.",
         f"Top-left corner: latitude {north:.4f}, longitude {west:.4f} E. "
         f"Covers {span:.4f} degrees each way.",
         f"spacing_m={metres_per_pixel * TERRAIN_STRIDE:.0f}",
         "Generated by tools/fetch_nasa_data.py."],
        [f"c{i}" for i in range(n)],
        rows)


if __name__ == "__main__":
    steps = {"weather": weather, "events": events, "terrain": terrain}
    chosen = sys.argv[1:] or list(steps)
    for step in chosen:
        if step not in steps:
            raise SystemExit(f"unknown step {step!r}; choose from {', '.join(steps)}")
    for step in chosen:
        print(step + ":")
        steps[step]()
